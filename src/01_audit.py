import statsmodels.formula.api as smf

np.random.seed(150)
ROOT = Path(__file__).resolve().parents[1]
RAW, DOCS, TABLES = ROOT / "data/raw", ROOT / "docs", ROOT / "outputs/tables"
TABLES.mkdir(parents=True, exist_ok=True)

out = []  # markdown lines


def md(s=""):
    out.append(s)


def norm(name):
    """Accent-stripped lowercase key; drops 'extension'/'loan' suffixes used in record_transfers."""
    s = unicodedata.normalize("NFKD", str(name)).encode("ascii", "ignore").decode()
    s = re.sub(r"\b(extension|loan)\b", "", s.lower())
    return re.sub(r"[^a-z ]", "", s).strip()


mv = pd.read_csv(RAW / "player_market_values.csv")
rt = pd.read_csv(RAW / "record_transfers.csv")
th = pd.read_csv(RAW / "transfers_history.csv")
cf = pd.read_csv(RAW / "club_financials.csv")
lm = pd.read_csv(RAW / "league_metrics.csv")
sm = pd.read_excel(RAW / "football_players_social_media.xlsx")

md("# Data audit (PROJECT_BRIEF §6.1)")
md()
md("Generated by `src/01_audit.py`. Every count below is computed from `data/raw/`; re-run the script to reproduce.")
md()

# ---------------------------------------------------------------- shapes
md("## 0. File inventory")
md()
md("| File | Rows | Cols | Missing cells |")
md("|---|---|---|---|")
for name, df in [("player_market_values.csv", mv), ("record_transfers.csv", rt),
                 ("transfers_history.csv", th), ("club_financials.csv", cf),
                 ("league_metrics.csv", lm), ("football_players_social_media.xlsx", sm)]:
    md(f"| `{name}` | {len(df):,} | {df.shape[1]} | {int(df.isna().sum().sum()):,} |")
md()

# ---------------------------------------------------------------- finding 1
md("## Finding 1: `transfers_history.csv` is synthetic. **CONFIRMED**")
md()
first = th.player_name.str.split().str[0]
last = th.player_name.str.split().str[-1]
n_names = th.player_name.nunique()
reps = th.player_name.value_counts()
multi = reps[reps > 1].index
birth_consistent = (th[th.player_name.isin(multi)].assign(by=lambda d: d.year - d.age)
                    .groupby("player_name").by.nunique().eq(1).sum())
mv_keys = set(mv.player_name.map(norm))
th_in_mv = th[th.player_name.map(norm).isin(mv_keys)]
md(f"- {len(th):,} rows, {n_names:,} unique names, built from only **{first.nunique()} first names × "
   f"{last.nunique()} surnames** ({first.nunique() * last.nunique():,} possible combinations; "
   f"{n_names / (first.nunique() * last.nunique()):.0%} of the grid is used). Real surnames are recombined at random "
   f"(e.g. {', '.join(th.player_name[last == 'Camavinga'].drop_duplicates().head(4))}).")
md(f"- Most repeated name: \"{reps.index[0]}\" ×{reps.iloc[0]}. Of {len(multi):,} names with >1 row, only "
   f"**{birth_consistent}** have a consistent implied birth year (year − age) across rows: rows are independent draws, not careers.")
md(f"- Fees are hard-capped: max = €{th.fee_eur_m.max():.0f}m, with **{(th.fee_eur_m == th.fee_eur_m.max()).sum()} rows at exactly the cap** "
   f"and **{(th.fee_eur_m >= 100).sum():,} transfers ≥ €100m** (the real market has had well under 100 such deals in history).")
md(f"- Every year 2010–2026 has a €200m deal. Median fee by age is flat "
   f"(€{th.groupby('age').fee_eur_m.median().loc[16:32].min():.1f}m–€{th.groupby('age').fee_eur_m.median().loc[16:32].max():.1f}m for ages 16–32); "
   f"by position €{th.groupby('position').fee_eur_m.median().min():.1f}m–€{th.groupby('position').fee_eur_m.median().max():.1f}m. "
   "Real fees fall steeply after ~28 and vary strongly by position.")
md(f"- Linkage to the 85 market-value players: {th_in_mv.player_name.nunique()} name(s), {len(th_in_mv)} rows "
   f"({'; '.join(f'{r.player_name} {r.year} age {r.age} {r.from_club}→{r.to_club} €{r.fee_eur_m}m' for r in th_in_mv.itertuples())}). "
   "None match the real player's age or career.")
md(f"- Structure is internally neat: {th.from_club.nunique()} clubs, {th.from_league.nunique()} leagues, "
   f"{(th.from_club == th.to_club).sum()} self-transfers, no missing cells. That neatness plus the above is typical of a generated dataset.")
md("- Aggregate year trend (median fee €{:.1f}m in 2010 → €{:.1f}m in 2026) is smooth and could be a programmed inflation term; "
   "it is **not** evidence of real market conditions.".format(*th.groupby("year").fee_eur_m.median().loc[[2010, 2026]]))
md()
md("**Implication:** not usable at player level, and not trustworthy even for aggregate market context. Recommend dropping it "
   "(pending group confirmation of its provenance).")
md()

# ---------------------------------------------------------------- finding 2
md("## Finding 2: market values are stylized (an age curve, not market data). **CONFIRMED**")
md()
mv["lmv"] = np.log(mv.market_value_eur_m.clip(lower=0.1))
# peak age per player (first peak row, or argmax)
peak = mv.loc[mv.groupby("player_name").market_value_eur_m.idxmax(), ["player_name", "age"]].rename(columns={"age": "peak_age"})
mvp = mv.merge(peak, on="player_name")
mvp["yfp"] = (mvp.age - mvp.peak_age).clip(-12, 10)
r2_age = smf.ols("lmv ~ C(age)", mvp).fit().rsquared
r2_age_fe = smf.ols("lmv ~ C(age) + C(player_name)", mvp).fit().rsquared
r2_yfp = smf.ols("lmv ~ C(yfp)", mvp).fit().rsquared
r2_yfp_fe = smf.ols("lmv ~ C(yfp) + C(player_name)", mvp).fit().rsquared
med_by_age = mv.groupby("age").market_value_eur_m.median()
old = mv[mv.age >= 31]
md(f"- 85 players, {len(mv):,} player-years, {mv.year.min()}–{mv.year.max()}.")
md(f"- Share of variance in log market value explained by **age dummies alone: R² = {r2_age:.2f}**; "
   f"by **years-from-own-peak alone: R² = {r2_yfp:.2f}**; years-from-peak + player FE: R² = {r2_yfp_fe:.2f}. "
   "A single template curve, shifted to each player's peak, reproduces almost all of the series.")
md(f"- Median value by age: €{med_by_age.loc[18]:.1f}m at 18, €{med_by_age.loc[26]:.1f}m at 26, "
   f"€{med_by_age.loc[30]:.1f}m at 30, €{med_by_age.loc[32]:.1f}m at 32. "
   f"{(old.market_value_eur_m < 10).mean():.0%} of player-years at age ≥ 31 are under €10m, regardless of who the player is.")
md(f"- Peaks: {mv.is_peak_year.sum()} rows flagged `is_peak_year` across {mv.player_name.nunique()} players; "
   f"peak age median {peak.peak_age.median():.0f} (IQR {peak.peak_age.quantile(.25):.0f}–{peak.peak_age.quantile(.75):.0f}).")
md()

# Reference values: widely reported Transfermarkt valuations, rounded. Approximate; must be confirmed on transfermarkt.com
# before being cited. They are here to show order of magnitude, not to replace the formal 20+ player-year check.
ref = pd.DataFrame([
    ("Lionel Messi", 2010, 100), ("Lionel Messi", 2018, 180), ("Lionel Messi", 2023, 35),
    ("Kylian Mbappé", 2018, 200), ("Kylian Mbappé", 2024, 180), ("Kylian Mbappé", 2025, 180),
    ("Harry Kane", 2018, 150), ("Harry Kane", 2023, 110),
    ("Neymar", 2018, 180), ("Neymar", 2022, 75),
    ("Cristiano Ronaldo", 2018, 100),
    ("Erling Haaland", 2024, 180), ("Jude Bellingham", 2024, 180),
    ("Robert Lewandowski", 2021, 60), ("Luka Modric", 2018, 25), ("Karim Benzema", 2022, 30),
    ("Kevin De Bruyne", 2018, 150), ("Mohamed Salah", 2018, 150), ("Virgil van Dijk", 2019, 100),
], columns=["player_name", "year", "ref_tm_eur_m_approx"])
ref = ref.merge(mv[["player_name", "year", "age", "market_value_eur_m"]], on=["player_name", "year"], how="left")
ref["ratio_file_to_ref"] = (ref.market_value_eur_m / ref.ref_tm_eur_m_approx).round(2)
ref.to_csv(TABLES / "audit_mv_reference_check.csv", index=False)
md("Spot check against widely reported Transfermarkt values (**approximate, from public reporting; each must be confirmed "
   "on Transfermarkt before citing**; saved to `outputs/tables/audit_mv_reference_check.csv`):")
md()
md("| Player | Year | Age | File €m | Reported TM ≈ €m | File / TM |")
md("|---|---|---|---|---|---|")
for r in ref.itertuples():
    fv = "n/a" if pd.isna(r.market_value_eur_m) else f"{r.market_value_eur_m:.1f}"
    ag = "" if pd.isna(r.age) else int(r.age)
    md(f"| {r.player_name} | {r.year} | {ag} | {fv} | {r.ref_tm_eur_m_approx} | {r.ratio_file_to_ref if pd.notna(r.ratio_file_to_ref) else 'n/a'} |")
md()
ok = ref.ratio_file_to_ref.between(0.67, 1.5).sum()
md(f"{ok} of {ref.ratio_file_to_ref.notna().sum()} spot checks fall within ±50% of the reported value. "
   "Errors are not random: the file is close near each player's peak and collapses at ~30+ (Kane 2023, Messi 2023, Mbappé 2025, "
   "Modric 2018, Benzema 2022) and before the breakout (Messi 2010).")
md()
# fee vs mv_{t-1} for linked transfers
mv_k = mv.assign(key=mv.player_name.map(norm))
md("**Inconsistency with `record_transfers` (the files contradict each other):**")
md()
md("| Transfer | Fee €m | File mv(t−1) €m | File mv(t) €m | Fee / mv(t−1) |")
md("|---|---|---|---|---|")
paid = rt[(rt.is_free_transfer == 0) & (rt.is_loan == 0) & (rt.is_extension == 0)].copy()
paid["key"] = paid.player_name.map(norm)
lk = (paid.merge(mv_k[["key", "year", "market_value_eur_m"]].rename(columns={"market_value_eur_m": "mv_t"}), on=["key", "year"], how="left")
          .merge(mv_k[["key", "year", "market_value_eur_m"]].assign(year=lambda d: d.year + 1)
                 .rename(columns={"market_value_eur_m": "mv_tm1"}), on=["key", "year"], how="left"))
lk = lk.drop_duplicates("transfer_id")  # Saka duplicates would fan out; none of his rows are transfers
for r in lk[lk.mv_tm1.notna() | lk.mv_t.notna()].itertuples():
    ratio = "" if pd.isna(r.mv_tm1) else f"{r.fee_eur_m / r.mv_tm1:.1f}×"
    md(f"| {r.player_name} {r.year} | {r.fee_eur_m:g} | {'' if pd.isna(r.mv_tm1) else f'{r.mv_tm1:g}'} | "
       f"{'' if pd.isna(r.mv_t) else f'{r.mv_t:g}'} | {ratio} |")
md()
md("**Implication:** with this series as the outcome, \"value\" is mostly a deterministic function of age and peak timing, and "
   "`premium = log(fee) − log(mv_{t−1})` is dominated by the curve's artefacts (e.g. Kane's 'premium' is an artefact of the collapse "
   "at 30). Neither outcome A nor C can be estimated credibly on it.")
md()

