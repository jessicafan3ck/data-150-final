md(f"- Market-value players without an exact normalised match ({len(unmatched_mv)}): {', '.join(unmatched_mv)}. "
   "These go into `docs/name_crosswalk.csv` for manual review (fuzzy candidates are listed there, `reviewed = 0`).")
# fuzzy candidates for crosswalk
import difflib
cands = []
pool = sorted(soc_keys)
for p in mv_players:
    k = norm(p)
    best = k if k in soc_keys else (difflib.get_close_matches(k, pool, n=1, cutoff=0.75) or [""])[0]
    cands.append(dict(source_name=p, source_file="player_market_values", key=k, social_match=best,
                      match_type="exact" if best == k else ("fuzzy" if best else "none"), reviewed=0))
for p in paid.player_name.drop_duplicates():
    k = norm(p)
    best = k if k in soc_keys else (difflib.get_close_matches(k, pool, n=1, cutoff=0.75) or [""])[0]
    cands.append(dict(source_name=p, source_file="record_transfers", key=k, social_match=best,
                      match_type="exact" if best == k else ("fuzzy" if best else "none"), reviewed=0))
cw = pd.DataFrame(cands).drop_duplicates(["source_name", "source_file"])
cw.to_csv(DOCS / "name_crosswalk.csv", index=False)
md(f"- Crosswalk written: {len(cw)} rows ({(cw.match_type == 'exact').sum()} exact, {(cw.match_type == 'fuzzy').sum()} fuzzy, "
   f"{(cw.match_type == 'none').sum()} none).")
md()

