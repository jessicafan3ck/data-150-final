"""08_club_context.py: part 1, context. How club finances work and how the price of attention has changed.

1. Club finance trends from club_financials.csv (52 clubs, 2010-2026): revenue, wages, net transfer spend.
2. Where club money comes from: UEFA aggregates (published figures, see docs/data_sources.md).
3. Price of attention over time: panel model A with log_wiki12 interacted with period.
Writes outputs/tables/context_*.csv, outputs/figures/context_*.png, docs/results_context.md.
"""
from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.formula.api as smf

import viz_style as vs
from viz_style import plt

ROOT = Path(__file__).resolve().parents[1]
RAW, CLEAN, TABLES, FIGS, DOCS = (ROOT / p for p in ("data/raw", "data/clean", "outputs/tables", "outputs/figures",
                                                      "docs"))
LN2 = np.log(2)
BIG5 = ["Premier_League", "La_Liga", "Bundesliga", "Serie_A", "Ligue_1"]
LEAGUE_LABEL = {"Premier_League": "Premier League", "La_Liga": "La Liga", "Bundesliga": "Bundesliga",
                "Serie_A": "Serie A", "Ligue_1": "Ligue 1", "Other": "Other leagues"}

# UEFA published aggregates for European top-division clubs (sources in docs/data_sources.md)
UEFA = pd.DataFrame([
    ("Operating revenue, 2024", 28.6, "UEFA, European Club Finance and Investment Landscape (2026)"),
    ("Player wages, 2024", 13.5, "UEFA / Football Benchmark summary of the same report"),
    ("Player sales, summer 2026 window", 10.3, "UEFA, The key trends at the heart of European club football (2026)"),
    ("Transfer spending, summer 2026 window", 10.0, "same; 'broke the EUR 10bn barrier', so 10.0 is a lower bound"),
    ("Projected transfer profit from that window", 6.8, "same; booked in 2026 and 2027 accounts"),
], columns=["item", "eur_bn", "source"])
SALES_SHARE = 10.3 / 28.6  # player sales per euro of operating revenue, used as the central case in 09

md = ["# Part 1: context — club finances and the changing price of attention", "",
      "Generated by `src/08_club_context.py`. Club figures use the supplied `club_financials.csv` as given.", ""]

# ---------------------------------------------------------------- 1. club finance trends
cf = pd.read_csv(RAW / "club_financials.csv")
cf["league_grp"] = np.where(cf.league.isin(BIG5), cf.league, "Other")
by_year = cf.groupby("year").agg(clubs=("club_name", "nunique"), revenue=("revenue_eur_m", "sum"),
                                 wages=("wage_bill_eur_m", "sum"), net_spend=("net_transfer_spend_eur_m", "sum"),
                                 net_sellers=("net_transfer_spend_eur_m", lambda s: (s < 0).mean()))
by_year["wages_pct"] = by_year.wages / by_year.revenue * 100
by_year["net_spend_pct"] = by_year.net_spend / by_year.revenue * 100
by_year.to_csv(TABLES / "context_club_finance_by_year.csv")
by_league = cf.groupby(["league_grp", "year"]).revenue_eur_m.sum().unstack(0)
by_league.to_csv(TABLES / "context_revenue_by_league.csv")
# net transfer spend relative to revenue, by club over the whole period: who funds itself by selling?
club = cf.groupby(["club_name", "league"]).agg(revenue=("revenue_eur_m", "sum"),
                                                net_spend=("net_transfer_spend_eur_m", "sum")).reset_index()
club["net_spend_pct"] = club.net_spend / club.revenue * 100
club.sort_values("net_spend_pct").to_csv(TABLES / "context_club_net_spend.csv", index=False)
UEFA.to_csv(TABLES / "context_uefa_aggregates.csv", index=False)

y0, y1 = by_year.index.min(), 2025
g = by_year.loc[y1, "revenue"] / by_year.loc[y0, "revenue"] - 1
md += ["## 1. How club finances work", "",
       f"- The 52 clubs' combined revenue grew from €{by_year.loc[y0, 'revenue'] / 1e3:.1f}bn in {y0} to "
       f"€{by_year.loc[y1, 'revenue'] / 1e3:.1f}bn in {y1} (+{g:.0%}). Wages take a steady "
       f"{by_year.wages_pct.min():.0f}–{by_year.wages_pct.max():.0f}% of revenue.",
       f"- Net transfer spend is small next to revenue on aggregate ({by_year.net_spend_pct.mean():+.1f}% of revenue "
       f"per year on average), because one club's purchase is another's sale. In a typical year "
       f"{by_year.net_sellers.mean():.0%} of these clubs are net sellers.",
       f"- Across Europe's top divisions (UEFA), clubs sold €10.3bn of players in the summer 2026 window alone, "
       f"against €28.6bn of operating revenue in 2024: roughly **€{SALES_SHARE * 100:.0f} of player sales for every "
       f"€100 of operating revenue**, and €6.8bn of that is expected to be profit. Player sales are a second income "
       "stream about a third the size of everything else a club earns.",
       "- The supplied `transfers_history.csv` is not used for gross flows: it implies the median club sells about "
       "twice its annual revenue in players each year, which does not fit `club_financials.csv`.", "",
       "Clubs most reliant on net sales over 2010–2026 (net transfer spend as % of revenue):", "",
       club.sort_values("net_spend_pct").head(8)[["club_name", "league", "net_spend_pct"]]
       .round(1).to_markdown(index=False), ""]

# ---------------------------------------------------------------- 2. price of attention over time
pan = pd.read_csv(CLEAN / "panel.csv").dropna(subset=["log_mv", "P", "log_wiki12", "wiki_growth", "league"])
pan["pos"] = pan.position
PERIODS = {2017: "2017–18", 2018: "2017–18", 2019: "2019–20", 2020: "2019–20", 2021: "2021–22", 2022: "2021–22",
           2023: "2023–25", 2024: "2023–25", 2025: "2023–25"}
pan["period"] = pan.year.map(PERIODS)
m = smf.ols("log_mv ~ age + I(age**2) + C(pos) + C(year) + C(league) + P + wiki_growth + log_wiki12:C(period)",
            pan).fit(cov_type="cluster", cov_kwds={"groups": pd.factorize(pan.player_name)[0]})
rows = []
for per in sorted(pan.period.unique()):
    term = f"log_wiki12:C(period)[{per}]"
    lo, hi = m.conf_int().loc[term]
    rows.append(dict(period=per, n=int((pan.period == per).sum()),
                     pct_per_doubling=(np.exp(m.params[term] * LN2) - 1) * 100,
                     ci_lo=(np.exp(lo * LN2) - 1) * 100, ci_hi=(np.exp(hi * LN2) - 1) * 100))
per_tab = pd.DataFrame(rows)
per_tab.to_csv(TABLES / "context_attention_by_period.csv", index=False)
fee_mv = pd.read_csv(TABLES / "eda_fee_to_mv_by_year.csv")
md += ["## 2. Has the price of attention changed?", "",
       "Market-value model A with the attention slope allowed to differ by period "
       "(same controls as the headline model; 95% CIs, SEs clustered by player):", "",
       per_tab.round(1).to_markdown(index=False), "",
       "Read with care: each period has 40–70 players a year and the intervals overlap.", ""]

# ---------------------------------------------------------------- figures
fig, ax = plt.subplots(figsize=(7.5, 4))
fig.subplots_adjust(top=0.84)
order = BIG5 + ["Other"]
cols = [vs.SEQ_BLUE[6], vs.SEQ_BLUE[5], vs.SEQ_BLUE[4], vs.SEQ_BLUE[3], vs.SEQ_BLUE[2], vs.MUTED]
ax.stackplot(by_league.index, [by_league[c] / 1e3 for c in order], colors=cols, edgecolor=vs.SURFACE, lw=0.8)
for c, colr, cum in zip(order, cols, (by_league[order].cumsum(axis=1) - by_league[order] / 2).loc[2026] / 1e3):
    ax.text(2026.3, cum, LEAGUE_LABEL[c], va="center", fontsize=8.5, color=vs.INK2)
ax.set_xlim(2010, 2026)
ax.set_ylabel("Revenue, € billion")
ax.grid(axis="x", visible=False)
ax.spines[["left", "bottom"]].set_visible(False)
ax.tick_params(length=0)
fig.text(0.01, 1.0, "Combined revenue of the 52 clubs in the data, by league", fontsize=13, fontweight="bold",
         ha="left", va="bottom")
fig.text(0.01, 0.985, "2010–2026, € billion", fontsize=9.5, color=vs.INK2, ha="left", va="top")
fig.savefig(FIGS / "context_1_club_revenue.png"); plt.close(fig)

fig, ax = plt.subplots(figsize=(7.5, 2.8))
fig.subplots_adjust(top=0.78, left=0.36)
u = UEFA.iloc[[0, 2, 4, 1]]
labels = ["Operating revenue (2024)", "Player sales (one window, summer 2026)", "Profit on those sales",
          "Player wages (2024)"]
colors = [vs.BLUE, vs.ORANGE, vs.ORANGE, vs.MUTED]
ax.barh(range(4), u.eur_bn, color=colors, height=0.6)
for i, v in enumerate(u.eur_bn):
    ax.text(v + 0.3, i, f"€{v:.1f}bn", va="center", fontsize=9.5, color=vs.INK)
ax.set_yticks(range(4), labels)
ax.invert_yaxis()
ax.set_xticks([])
ax.grid(False)
ax.spines[["left", "bottom"]].set_visible(False)
ax.tick_params(length=0)
fig.text(0.01, 1.0, "Money in and out of European top-division clubs", fontsize=13, fontweight="bold",
         ha="left", va="bottom")
fig.text(0.01, 0.985, "€ billion, all top-division clubs in Europe. Source: UEFA", fontsize=9.5, color=vs.INK2,
         ha="left", va="top")
fig.savefig(FIGS / "context_2_money_in.png"); plt.close(fig)

fig, ax = plt.subplots(figsize=(7.5, 3.4))
fig.subplots_adjust(top=0.8)
x = np.arange(len(per_tab))
ax.vlines(x, per_tab.ci_lo, per_tab.ci_hi, color=vs.BLUE, lw=3)
ax.scatter(x, per_tab.pct_per_doubling, s=80, color=vs.BLUE, edgecolor=vs.SURFACE, linewidth=2, zorder=3)
for i, r in per_tab.iterrows():
    ax.text(i + 0.12, r.pct_per_doubling, f"{r.pct_per_doubling:+.0f}%".replace("-", "−"), va="center",
            fontsize=10, fontweight="bold", color=vs.INK)
ax.axhline(0, color=vs.INK2, lw=1)
ax.set_xticks(x, per_tab.period)
ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{v:+.0f}%".replace("-", "−") if v else "0"))
ax.grid(axis="x", visible=False)
ax.spines[["left", "bottom"]].set_visible(False)
ax.tick_params(length=0)
fig.text(0.01, 1.0, "Change in market value per doubling of Wikipedia attention, by period", fontsize=13,
         fontweight="bold", ha="left", va="bottom")
fig.text(0.01, 0.985, "Same performance, age and position. Bars show 95% confidence intervals.", fontsize=9.5,
         color=vs.INK2, ha="left", va="top")
fig.savefig(FIGS / "context_3_attention_by_period.png"); plt.close(fig)

(DOCS / "results_context.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
